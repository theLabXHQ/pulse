func writeFile(t *testing.T, name, content string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestLoadSystem(t *testing.T) {
	rc := writeFile(t, "resolv.conf", `# generated by WSL
nameserver 172.20.80.1
nameserver fe80::1%eth0
nameserver not-an-ip
nameserver 10.0.0.3
nameserver 10.0.0.4
domain ignored.example
search corp.example. lab.example
options ndots:99 timeout:5
`)
	hosts := writeFile(t, "hosts", "127.0.0.1 localhost\n10.1.1.1 intranet Intranet.Corp.Example. # comment\n# 10.9.9.9 commented\n")
	cfg, err := loadSystem(rc, hosts)
	if err != nil {
		t.Fatal(err)
	}
	var servers []string
	for _, s := range cfg.servers {
		servers = append(servers, s.String())
	}
	if got := strings.Join(servers, ","); got != "172.20.80.1:53,[fe80::1]:53,10.0.0.3:53" {
		t.Errorf("servers %s", got)
	}
	if strings.Join(cfg.search, ",") != "corp.example,lab.example" || cfg.ndots != 15 {
		t.Errorf("search %v ndots %d", cfg.search, cfg.ndots)
	}
	if cfg.hosts["intranet.corp.example"][0].String() != "10.1.1.1" || len(cfg.hosts["10.9.9.9"]) != 0 {
		t.Errorf("hosts %v", cfg.hosts)
	}
	if _, err := loadSystem(writeFile(t, "empty.conf", "search x\n"), hosts); err == nil {
		t.Error("resolv.conf without servers must be rejected (Go's resolver takes over)")
	}
	cfg, _ = loadSystem(writeFile(t, "d.conf", "nameserver 1.1.1.1\ndomain only.example\n"), "/nonexistent")
	if strings.Join(cfg.search, ",") != "only.example" {
		t.Errorf("domain without search: %v", cfg.search)
	}
}

func TestCandidatesFollowNdots(t *testing.T) {
	s := &systemResolver{cfg: &systemConfig{ndots: 1, search: []string{"corp.example"}}}
	if got := strings.Join(s.candidates("www.example.com"), ","); got != "www.example.com,www.example.com.corp.example" {
		t.Errorf("dotted name: %s", got)
	}
	if got := strings.Join(s.candidates("intranet"), ","); got != "intranet.corp.example,intranet" {
		t.Errorf("single label: %s", got)
	}
	s.cfg.search = nil
	if got := strings.Join(s.candidates("intranet"), ","); got != "intranet" {
		t.Errorf("no search list: %s", got)
	}
}

func TestSystemResolverHostsAndSearch(t *testing.T) {
	addr, queries := fakeDNS(t, 0) // answers *.ok.test
	rc := writeFile(t, "resolv.conf", "nameserver 127.0.0.1\nsearch ok.test\n")
	hosts := writeFile(t, "hosts", "10.1.1.1 fileonly.test\n")
	r := New(Options{ResolvConf: rc, HostsFile: hosts})
	if r.sys == nil {
		t.Fatal("system UDP resolver not set up")
	}
	// resolv.conf cannot carry a port; point the client at the fake server.
	u, err := newUDPClient([]netip.AddrPort{netip.MustParseAddrPort(addr)}, false, r.net)
	if err != nil {
		t.Fatal(err)
	}
	r.sys.udp = u

	if ips, err := r.Lookup(context.Background(), "fileonly.test"); err != nil || ips[0].String() != "10.1.1.1" || queries.Load() != 0 {
		t.Fatalf("hosts file: %v %v (queries %d)", ips, err, queries.Load())
	}
	if ips, err := r.Lookup(context.Background(), "www"); err != nil || len(ips) != 1 || ips[0].String() != "192.0.2.7" {
		t.Fatalf("search list: %v %v", ips, err)
	}
	// With the search list, "missing.example" would be retried as
	// missing.example.ok.test (which the fake answers), as glibc does.
	r.sys.cfg.search = nil
	_, err = r.Lookup(context.Background(), "missing.example")
	var de *net.DNSError
	if !errors.As(err, &de) || !de.IsNotFound || de.Name != "missing.example" {
		t.Fatalf("NXDOMAIN must carry the queried name: %#v", err)
	}
}

func TestHostsFileSurvivesFallback(t *testing.T) {
	good, _ := fakeDNS(t, 0)
	hosts := writeFile(t, "hosts", "10.1.2.3 myhost\n")
	r := New(Options{Fallback: []string{good}, HostsFile: hosts, ResolvConf: writeFile(t, "r", "nameserver 127.0.0.1\n"), Timeout: 200 * time.Millisecond})
	silentSystem(t, r)
	r.CheckSystem(100 * time.Millisecond)
	if !r.UsingFallback() {
		t.Fatal("expected the fallback")
	}
	if ips, err := r.Lookup(context.Background(), "myhost"); err != nil || len(ips) != 1 || ips[0].String() != "10.1.2.3" {
		t.Fatalf("hosts file ignored on the fallback: %v %v", ips, err)
	}
}

func TestLookupCNAMEChain(t *testing.T) {
	chain := map[string]string{"www.c.test.": "edge.cdn.test.", "edge.cdn.test.": "final.cdn.test."}
	pc, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer pc.Close()
	go func() {
		buf := make([]byte, 1500)
		for {
			n, from, err := pc.ReadFrom(buf)
			if err != nil {
				return
			}
			var p dnsmessage.Parser
			h, err := p.Start(buf[:n])
			if err != nil {
				continue
			}
			q, err := p.Question()
			if err != nil {
				continue
			}
			b := dnsmessage.NewBuilder(nil, dnsmessage.Header{ID: h.ID, Response: true})
			_ = b.StartQuestions()
			_ = b.Question(q)
			_ = b.StartAnswers()
			if target, ok := chain[strings.ToLower(q.Name.String())]; ok && q.Type == dnsmessage.TypeCNAME {
				_ = b.CNAMEResource(dnsmessage.ResourceHeader{Name: q.Name, Class: dnsmessage.ClassINET, TTL: 60},
					dnsmessage.CNAMEResource{CNAME: dnsmessage.MustNewName(target)})
			}
			out, _ := b.Finish()
			_, _ = pc.WriteTo(out, from)
		}
	}()
	r := New(Options{Servers: []string{pc.LocalAddr().String()}})
	got, err := r.LookupCNAME(context.Background(), "www.c.test")
	if err != nil || strings.Join(got, ",") != "edge.cdn.test,final.cdn.test" {
		t.Fatalf("got %v %v", got, err)
	}
	if got, _ := r.LookupCNAME(context.Background(), "plain.test"); len(got) != 0 {
		t.Fatalf("no CNAME: %v", got)
	}
}
